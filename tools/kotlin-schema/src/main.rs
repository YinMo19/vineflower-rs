use std::{
    collections::{BTreeMap, BTreeSet},
    env,
    fmt::Write,
    fs,
    path::{Path, PathBuf},
    process::Command,
};

use heck::{ToSnakeCase, ToUpperCamelCase};
use prost::Message;
use prost_types::{
    DescriptorProto, FieldDescriptorProto, FileDescriptorSet,
    field_descriptor_proto::{Label, Type},
};

const CORE: &str = "org.jetbrains.kotlin.metadata";
const JVM: &str = "org.jetbrains.kotlin.metadata.jvm";
const SCHEMAS: &str = "// Source schemas: JetBrains/kotlin v2.2.20 metadata.proto and jvm_metadata.proto.\n\
     // Regenerate using tools/kotlin-schema.\n";

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let descriptor_path = env::args_os()
        .nth(1)
        .ok_or("expected a FileDescriptorSet path")?;
    let mut descriptor = FileDescriptorSet::decode(fs::read(descriptor_path)?.as_slice())?;
    descriptor.file.retain(|file| {
        matches!(
            file.name(),
            "core/metadata/src/metadata.proto" | "core/metadata.jvm/src/jvm_metadata.proto"
        )
    });
    if descriptor.file.len() != 2 {
        return Err("expected schemas from the Kotlin repository root".into());
    }
    inline_extensions(&mut descriptor);

    let mut messages = BTreeMap::new();
    for file in &mut descriptor.file {
        let pkg = file.package.clone().unwrap();
        for message in &mut file.message_type {
            prepare(message, &format!(".{pkg}"), &mut messages);
        }
    }
    let out = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/kotlin/metadata");
    let mut config = prost_build::Config::new();
    let files = config.generate(
        descriptor
            .file
            .iter()
            .map(|file| {
                (
                    prost_build::Module::from_protobuf_package_name(file.package()),
                    file.clone(),
                )
            })
            .collect(),
    )?;
    for (package, filename) in [(CORE, "proto.rs"), (JVM, "jvm_proto.rs")] {
        let text = &files[&prost_build::Module::from_protobuf_package_name(package)];
        let jvm_module = if package == CORE {
            "\npub mod jvm {\n    include!(\"jvm_proto.rs\");\n}\n"
        } else {
            ""
        };
        let text = format!(
            "// Generated by prost-build with the Kotlin schema generator.\n\
             {SCHEMAS}// JVM extensions are fields on their host messages.\n\
             // Proto2 required fields retain presence for recursive validation.\n\n\
             {text}{jvm_module}"
        );
        write_rust(&out.join(filename), &text)?;
    }
    write_rust(&out.join("wire_checks.rs"), &wire_checks(&messages))?;
    Ok(())
}

fn inline_extensions(descriptor: &mut FileDescriptorSet) {
    let mut extensions = Vec::new();
    for file in &mut descriptor.file {
        // Kotlin's custom comparison options do not affect the wire types.
        file.dependency
            .retain(|dependency| dependency.ends_with("/metadata.proto"));
        extensions.append(&mut file.extension);
    }
    for mut field in extensions {
        let owner = field.extendee.take().unwrap();
        let (package, name) = owner[1..].rsplit_once('.').unwrap();
        let containing = descriptor
            .file
            .iter_mut()
            .find(|file| file.package() == package)
            .and_then(|file| {
                file.message_type
                    .iter_mut()
                    .find(|message| message.name() == name)
            })
            .unwrap();
        match (name, field.name()) {
            ("Property", "flags") => field.name = Some("jvm_flags".to_owned()),
            // The plugin's optimized jar names these extensions like their
            // respective built-in annotation fields. Their wire tags agree.
            (_, "type_annotation" | "type_parameter_annotation") => {
                field.name = Some("annotation".to_owned());
            }
            _ => {}
        }
        containing.field.push(field);
    }
}

fn prepare(
    message: &mut DescriptorProto,
    prefix: &str,
    messages: &mut BTreeMap<String, Vec<FieldDescriptorProto>>,
) {
    let name = format!("{prefix}.{}", message.name());
    messages.insert(name.clone(), message.field.clone());
    for field in &mut message.field {
        if field.label() == Label::Required {
            field.set_label(Label::Optional);
        }
        // The Java lite runtime preserves invalid UTF-8 in a String field
        // until a reader requests the text.
        if field.r#type() == Type::String {
            field.set_type(Type::Bytes);
        }
    }
    message.extension_range.clear();
    for child in &mut message.nested_type {
        prepare(child, &name, messages);
    }
}

fn wire_checks(messages: &BTreeMap<String, Vec<FieldDescriptorProto>>) -> String {
    let mut needed: BTreeSet<_> = messages
        .iter()
        .filter(|(_, fields)| {
            fields
                .iter()
                .any(|field| field.label() == Label::Required || field.r#type() == Type::Enum)
        })
        .map(|(name, _)| name.as_str())
        .collect();
    loop {
        let old_len = needed.len();
        for (name, fields) in messages {
            if fields
                .iter()
                .any(|field| needed.contains(field.type_name()))
            {
                needed.insert(name);
            }
        }
        if needed.len() == old_len {
            break;
        }
    }
    let mut output = format!(
        "// Generated by the Kotlin schema generator.\n{SCHEMAS}\n{}",
        include_str!("wire_checks.inc.rs"),
    );
    for name in needed.iter().copied() {
        let mut required = Vec::new();
        let mut optional = Vec::new();
        let mut repeated = Vec::new();
        let mut enums = Vec::new();
        for field in &messages[name] {
            let field_name = rust_field(field.name());
            if field.label() == Label::Required {
                let owner = name.rsplit('.').next().unwrap();
                required.push(format!("{field_name}: \"{owner}.{}\"", field.name()));
            }
            if field.r#type() == Type::Enum && field.label() != Label::Repeated {
                let target = type_path(field.type_name());
                enums.push(format!("{field_name}: {target}"));
            }
            if field.r#type() == Type::Message && needed.contains(field.type_name()) {
                match field.label() {
                    Label::Repeated => repeated.push(field_name),
                    Label::Optional | Label::Required => optional.push(field_name),
                }
            }
        }
        writeln!(output, "\ncheck_wire!({};", type_path(name)).unwrap();
        for (kind, fields) in [
            ("required", required),
            ("optional", optional),
            ("repeated", repeated),
            ("enums", enums),
        ] {
            writeln!(output, "    {kind} [{}],", fields.join(", ")).unwrap();
        }
        writeln!(output, ");").unwrap();
    }
    output
}

fn write_rust(path: &Path, contents: &str) -> Result<(), Box<dyn std::error::Error>> {
    fs::write(path, contents)?;
    if !Command::new("rustfmt")
        .args(["--edition", "2024", "--config", "skip_children=true"])
        .arg(path)
        .status()?
        .success()
    {
        return Err(format!("rustfmt failed on {}", path.display()).into());
    }
    Ok(())
}

fn rust_field(name: &str) -> String {
    let name = name.to_snake_case();
    if name == "type" {
        "r#type".into()
    } else {
        name
    }
}

fn type_path(name: &str) -> String {
    let (prefix, rest) = name
        .strip_prefix(&format!(".{JVM}."))
        .map(|part| ("jvm::", part))
        .unwrap_or_else(|| ("", name.strip_prefix(&format!(".{CORE}.")).unwrap()));
    let mut parts = rest.split('.');
    let ty = parts.next_back().unwrap().to_upper_camel_case();
    let modules = parts
        .map(|part| format!("{}::", rust_field(part)))
        .collect::<String>();
    format!("{prefix}{modules}{ty}")
}
